<h1>Acceptable Use Policy</h1>
<span class="effective-date">Effective date: 11 August 2026</span>

<p>
  This Acceptable Use Policy ("<strong>AUP</strong>") applies to all users of
  the Noizes platform operated by <strong>Speccraft Media Ltd.</strong> It
  supplements our <a href="/legal/terms">Terms of Service</a>. Violations may
  result in content removal, account suspension, or termination.
</p>

<h2>1. Prohibited Content</h2>
<p>You may not upload, publish, or distribute content that:</p>
<ul>
  <li><strong>Infringes intellectual property:</strong> Music, artwork, lyrics, or other material to which you do not hold the necessary rights or licences.</li>
  <li><strong>Is unlawful:</strong> Content that violates any applicable law or regulation in Kenya or the jurisdiction where you reside.</li>
  <li><strong>Is harmful or abusive:</strong> Content that promotes violence, terrorism, self-harm, or targets individuals or groups based on race, ethnicity, gender, sexual orientation, religion, disability, or other protected characteristics.</li>
  <li><strong>Is sexually explicit:</strong> Pornographic or sexually exploitative material, particularly any content involving minors.</li>
  <li><strong>Is deceptive:</strong> Content that impersonates another artist, misrepresents authorship, or is designed to deceive Collectors about the nature or origin of a release.</li>
  <li><strong>Contains malware:</strong> Files designed to damage, disrupt, or gain unauthorised access to devices or systems.</li>
  <li><strong>Is spam:</strong> Bulk, unsolicited, or repetitive content published primarily for promotional rather than artistic purposes.</li>
</ul>

<h2>2. Prohibited Conduct</h2>
<p>You may not:</p>
<ul>
  <li>Create multiple accounts to circumvent bans, edition limits, or other restrictions.</li>
  <li>Manipulate the Exchange through wash trading, price manipulation, or fake transactions.</li>
  <li>Harass, bully, or threaten other users through collector notes, transfers, or any other Platform feature.</li>
  <li>Attempt to extract, scrape, or systematically download content from the Platform.</li>
  <li>Redistribute <code>.nz</code> files through unauthorised channels or strip authenticity data from packages.</li>
  <li>Use the Platform to launder money, finance terrorism, or engage in any financial crime.</li>
  <li>Interfere with the Platform's infrastructure, security, or other users' access.</li>
</ul>

<h2>3. Collector Notes</h2>
<p>
  Collector notes are short personal reflections attached to your stewardship of
  an edition. Notes must not contain:
</p>
<ul>
  <li>Hate speech, harassment, or threats</li>
  <li>Advertising, spam, or external links</li>
  <li>Personal information about other individuals</li>
  <li>Obscene or offensive language directed at others</li>
</ul>
<p>
  We reserve the right to hide any note that violates this policy.
</p>

<h2>4. Enforcement</h2>
<p>
  We may take any of the following actions in response to a violation, at our
  sole discretion:
</p>
<ol>
  <li><strong>Warning:</strong> A notice to cease the violating activity.</li>
  <li><strong>Content removal:</strong> Removal or restriction of the offending content.</li>
  <li><strong>Account suspension:</strong> Temporary suspension of account access.</li>
  <li><strong>Account termination:</strong> Permanent removal of your account and forfeiture of unpaid earnings (for Creators).</li>
</ol>
<p>
  We will provide notice before enforcement where practicable, except in cases
  involving imminent harm, legal obligations, or ongoing illegal activity.
</p>

<h2>5. Reporting Violations</h2>
<p>
  If you encounter content or conduct that violates this policy, please report
  it to <a href="mailto:report@noizes.xyz">report@noizes.xyz</a> with as much
  detail as possible, including the release or user involved and the nature of
  the violation.
</p>

