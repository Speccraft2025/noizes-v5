<h1>Copyright &amp; Takedown Policy</h1>
<span class="effective-date">Effective date: 11 August 2026</span>

<p>
  <strong>Speccraft Media Ltd.</strong> ("<strong>Speccraft</strong>") respects
  intellectual property rights and expects all Creators and users of the Noizes
  platform to do the same. This policy explains how to report copyright
  infringement and how we handle takedown requests.
</p>

<h2>1. Reporting Copyright Infringement</h2>
<p>
  If you believe that content on Noizes infringes your copyright, please send a
  written notice to our designated copyright agent at
  <a href="mailto:copyright@noizes.xyz">copyright@noizes.xyz</a> containing:
</p>
<ol>
  <li>Your full legal name and contact information (email address, mailing address, and phone number).</li>
  <li>A description of the copyrighted work you claim has been infringed.</li>
  <li>A link to or description of the infringing material on Noizes, sufficient for us to locate it (e.g. the Drop Page URL or release title and artist name).</li>
  <li>A statement that you have a good-faith belief that use of the material is not authorised by the copyright owner, its agent, or the law.</li>
  <li>A statement, made under penalty of perjury, that the information in your notice is accurate and that you are the copyright owner or authorised to act on their behalf.</li>
  <li>Your physical or electronic signature.</li>
</ol>

<h2>2. How We Process Notices</h2>
<p>
  Upon receiving a valid takedown notice, we will:
</p>
<ol>
  <li><strong>Acknowledge receipt</strong> within two (2) business days.</li>
  <li><strong>Investigate</strong> the claim and, if it appears valid, promptly remove or disable access to the alleged infringing content.</li>
  <li><strong>Notify the Creator</strong> whose content was removed, providing them with a copy of the complaint (excluding your personal contact details if you request confidentiality).</li>
</ol>

<h2>3. Counter-Notice</h2>
<p>
  If you are a Creator and believe your content was removed in error or is not
  infringing, you may submit a counter-notice to
  <a href="mailto:copyright@noizes.xyz">copyright@noizes.xyz</a> containing:
</p>
<ol>
  <li>Your full legal name and contact information.</li>
  <li>Identification of the content that was removed and its location on the Platform before removal.</li>
  <li>A statement under penalty of perjury that you have a good-faith belief the content was removed as a result of mistake or misidentification.</li>
  <li>A statement that you consent to the jurisdiction of the courts of Nairobi, Kenya, and that you will accept service of process from the person who filed the original notice.</li>
  <li>Your physical or electronic signature.</li>
</ol>
<p>
  Upon receiving a valid counter-notice, we will forward it to the original
  complainant and restore the content within ten (10) business days, unless the
  complainant notifies us that they have filed a court action.
</p>

<h2>4. Repeat Infringers</h2>
<p>
  We maintain a policy of terminating accounts of users who are repeat
  infringers. A Creator who receives three (3) valid takedown notices within a
  twelve-month period will have their account permanently terminated and all
  remaining releases removed from the Exchange.
</p>

<h2>5. Effect of Takedown on Existing Editions</h2>
<p>
  When a release is taken down due to a copyright claim:
</p>
<ul>
  <li>The release is immediately removed from the Exchange and its Drop Page is disabled.</li>
  <li>No further sales or transfers of that release are permitted.</li>
  <li>Collectors who already own editions may retain their downloaded <code>.nz</code> files for personal use, but the editions can no longer be transferred or resold on the Platform.</li>
  <li>Provenance records remain in the ledger with a notation of the takedown.</li>
  <li>If the Creator successfully resolves the claim or submits a valid counter-notice, the release may be restored.</li>
</ul>

<h2>6. Good Faith</h2>
<p>
  Filing a false or bad-faith takedown notice or counter-notice may result in
  legal liability. We reserve the right to take action against individuals who
  abuse this process, including suspension of their Noizes account.
</p>

