<h2>1. Identity Verification</h2>
<p>
  Before publishing any release, you must complete our Know Your Customer (KYC)
  verification process. This requires submitting a government-issued photo ID and
  a matching selfie. Your documents are stored securely in a private storage
  bucket and are only reviewed by authorised Noizes personnel.
</p>
<p>
  You agree that the identity information you provide is accurate and current.
  Providing false identity information is grounds for immediate account
  termination and forfeiture of unpaid earnings.
</p>

