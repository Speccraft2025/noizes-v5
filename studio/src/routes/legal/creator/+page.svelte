<h3>5.2 Payouts</h3>
<p>
  Payouts are processed manually within seven (7) business days of each sale.
  Payout timing may vary during the early-access period as we build automated
  disbursement. We will notify you before any changes to payout procedures.
</p>
<p>
  All payouts are in Kenyan Shillings (KES) unless otherwise agreed. You are
  responsible for any applicable taxes on your earnings.
</p>

<h3>5.3 Minimum Payout</h3>
<p>
  We may set a minimum payout threshold. Any balance below the threshold carries
  forward to the next payout cycle. If your account is terminated or you
  withdraw, we will pay any outstanding balance above the threshold within 30
  days.
</p>

<h2>6. Cryptographic Signing</h2>
<p>
  When you publish a release, it is cryptographically signed using an Ed25519
  key pair generated and managed on your behalf by the Platform. Your private
  signing key is encrypted at rest and is used exclusively to attest the
  authenticity and integrity of your releases. You acknowledge that:
</p>
<ul>
  <li>The signing key is custodial — we hold and manage it on your behalf.</li>
  <li>The public key is associated with your verified identity and published with your releases.</li>
  <li>Signatures and provenance records are permanent and cannot be deleted.</li>
</ul>

<h2>7. Withdrawal &amp; Takedown</h2>
<p>
  You may withdraw a release from the Exchange at any time, which will prevent
  further sales. However:
</p>
<ul>
  <li>Collectors who already own editions retain their copies and playback rights.</li>
  <li>Provenance records for sold editions remain in the public ledger.</li>
  <li>Your Drop Page URL may display a "withdrawn" notice rather than being deleted.</li>
</ul>

