  non-exclusive, royalty-free licence to:
</p>
<ul>
  <li>Host, store, and deliver your content through the Platform, including the Exchange and Drop Pages.</li>
  <li>Package your content into the <code>.nz</code> format and distribute it to Collectors who acquire editions.</li>
  <li>Display your artist name, artwork, and release metadata for promotional and discovery purposes on the Platform.</li>
  <li>Generate previews, thumbnails, and excerpts of your content for display on the Exchange.</li>
</ul>
<p>
