</p>

<h2>3. Rights Declaration &amp; Authority</h2>
<p>
  For each release, you must declare the rights basis for every component
  (audio, artwork, lyrics, etc.) using the Studio's rights declaration system.
  By publishing, you confirm that:
</p>
<ul>
  <li>You own or have obtained all necessary rights, licences, and permissions for every component of the release.</li>
  <li>Your release does not infringe the copyright, trademark, privacy, publicity, or other rights of any third party.</li>
  <li>All credits and rights-holder information you provide is accurate.</li>
</ul>
<p>
  Noizes records your declarations but does not verify or make legal conclusions
  about the validity of your rights claims. You are solely responsible for
  ensuring you have the authority to publish.
</p>

<h2>4. Editions &amp; Pricing</h2>
<p>
  You set the edition type (limited or open), supply (for limited editions), and
  price for each release. Once a release is published and editions have been sold:
</p>
<ul>
  <li>You may not increase the supply of a limited edition.</li>
  <li>You may adjust the price of unsold editions.</li>
  <li>You may withdraw unsold editions from the Exchange.</li>
</ul>

